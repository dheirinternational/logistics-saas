import { pool } from "@/lib/db/db"

export type PushPlatform = "ios" | "android" | "web" | "unknown"

export type PushPayload = {
  title: string
  body: string
  data?: Record<string, unknown>
  sound?: "default" | null
  channelId?: string
}

export type PushDispatchResult = {
  attempted: number
  sent: number
  failed: number
  pruned: number
}

const EXPO_PUSH_ENDPOINT = "https://exp.host/--/api/v2/push/send"
const EXPO_PUSH_TOKEN_REGEX = /^Expo(nent)?PushToken\[[^\]]+\]$/
const EXPO_BATCH_SIZE = 100

let ensureTablePromise: Promise<void> | null = null

/**
 * Ensures `user_push_tokens` exists even if SQL migrations were not yet applied.
 */
export async function ensurePushTokensTable(): Promise<void> {
  if (!ensureTablePromise) {
    ensureTablePromise = pool
      .query(`
        CREATE TABLE IF NOT EXISTS public.user_push_tokens (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
          token text NOT NULL,
          platform text NOT NULL DEFAULT 'unknown',
          device_name text,
          app_version text,
          created_at timestamptz NOT NULL DEFAULT now(),
          updated_at timestamptz NOT NULL DEFAULT now(),
          last_used_at timestamptz,
          CONSTRAINT user_push_tokens_token_key UNIQUE (token),
          CONSTRAINT user_push_tokens_platform_check
            CHECK (platform IN ('ios', 'android', 'web', 'unknown'))
        );
        CREATE INDEX IF NOT EXISTS idx_user_push_tokens_user_id
          ON public.user_push_tokens(user_id);
      `)
      .then(() => undefined)
      .catch((err) => {
        ensureTablePromise = null
        throw err
      })
  }
  return ensureTablePromise
}

export function isValidExpoPushToken(token: string): boolean {
  return typeof token === "string" && EXPO_PUSH_TOKEN_REGEX.test(token.trim())
}

export function normalizePushPlatform(value: unknown): PushPlatform {
  if (typeof value !== "string") return "unknown"
  const lower = value.trim().toLowerCase()
  if (lower === "ios" || lower === "android" || lower === "web") {
    return lower
  }
  return "unknown"
}

export async function registerUserPushToken(params: {
  userId: number
  token: string
  platform?: unknown
  deviceName?: string | null
  appVersion?: string | null
}): Promise<void> {
  const cleanToken = params.token.trim()
  if (!isValidExpoPushToken(cleanToken)) {
    throw new Error("Invalid Expo push token format")
  }

  await ensurePushTokensTable()
  const platform = normalizePushPlatform(params.platform)
  const deviceName = params.deviceName ? String(params.deviceName).slice(0, 120) : null
  const appVersion = params.appVersion ? String(params.appVersion).slice(0, 40) : null

  await pool.query(
    `
    INSERT INTO public.user_push_tokens (
      user_id,
      token,
      platform,
      device_name,
      app_version,
      updated_at,
      last_used_at
    )
    VALUES ($1, $2, $3, $4, $5, NOW(), NOW())
    ON CONFLICT (token)
    DO UPDATE SET
      user_id = EXCLUDED.user_id,
      platform = EXCLUDED.platform,
      device_name = COALESCE(EXCLUDED.device_name, public.user_push_tokens.device_name),
      app_version = COALESCE(EXCLUDED.app_version, public.user_push_tokens.app_version),
      updated_at = NOW(),
      last_used_at = NOW()
    `,
    [params.userId, cleanToken, platform, deviceName, appVersion],
  )
}

export async function unregisterUserPushToken(params: {
  userId: number
  token?: string | null
}): Promise<number> {
  const cleanToken = params.token?.trim()
  if (!cleanToken) return 0

  await ensurePushTokensTable()
  const res = await pool.query(
    `
    DELETE FROM public.user_push_tokens
    WHERE user_id = $1 AND token = $2
    `,
    [params.userId, cleanToken],
  )
  return res.rowCount ?? 0
}

function formatPreviewBody(text: string, maxLength = 200): string {
  const collapsed = text.replace(/\s+/g, " ").trim()
  if (!collapsed) return "You have a new update from DHEIR International."
  if (collapsed.length <= maxLength) return collapsed
  return `${collapsed.slice(0, maxLength - 1).trimEnd()}…`
}

async function pruneDeadTokens(tokens: string[]): Promise<number> {
  if (tokens.length === 0) return 0
  try {
    const res = await pool.query(
      `DELETE FROM public.user_push_tokens WHERE token = ANY($1::text[])`,
      [tokens],
    )
    return res.rowCount ?? 0
  } catch (err) {
    console.warn("Failed pruning stale push tokens:", err)
    return 0
  }
}

async function sendToTokens(tokens: string[], payload: PushPayload): Promise<PushDispatchResult> {
  const uniqueTokens = Array.from(
    new Set(tokens.map((t) => t.trim()).filter((t) => isValidExpoPushToken(t))),
  )
  if (uniqueTokens.length === 0) {
    return { attempted: 0, sent: 0, failed: 0, pruned: 0 }
  }

  const cleanTitle = payload.title.trim() || "DHEIR International"
  const cleanBody = formatPreviewBody(payload.body)
  const accessToken = process.env.EXPO_ACCESS_TOKEN?.trim()

  const headers: Record<string, string> = {
    Accept: "application/json",
    "Accept-Encoding": "gzip, deflate",
    "Content-Type": "application/json",
  }
  if (accessToken) {
    headers.Authorization = `Bearer ${accessToken}`
  }

  let sent = 0
  let failed = 0
  const deadTokens: string[] = []

  for (let i = 0; i < uniqueTokens.length; i += EXPO_BATCH_SIZE) {
    const batch = uniqueTokens.slice(i, i + EXPO_BATCH_SIZE)
    const messages = batch.map((to) => ({
      to,
      title: cleanTitle,
      body: cleanBody,
      sound: payload.sound === null ? undefined : payload.sound ?? "default",
      channelId: payload.channelId || "default",
      priority: "high",
      data: payload.data || {},
    }))

    try {
      const response = await fetch(EXPO_PUSH_ENDPOINT, {
        method: "POST",
        headers,
        body: JSON.stringify(messages),
        signal: AbortSignal.timeout(8000),
      })

      if (!response.ok) {
        const errText = await response.text().catch(() => response.statusText)
        console.warn("Expo push API HTTP error:", response.status, errText)
        failed += batch.length
        continue
      }

      const json = (await response.json().catch(() => null)) as {
        data?: Array<{
          status?: string
          message?: string
          details?: { error?: string }
        }>
      } | null

      const tickets = Array.isArray(json?.data) ? json.data : []
      batch.forEach((token, idx) => {
        const ticket = tickets[idx]
        if (!ticket || ticket.status === "ok") {
          sent += 1
        } else {
          failed += 1
          if (ticket.details?.error === "DeviceNotRegistered") {
            deadTokens.push(token)
          } else {
            console.warn("Expo push ticket error:", ticket.message, ticket.details)
          }
        }
      })
    } catch (err) {
      console.warn("Expo push dispatch error:", err)
      failed += batch.length
    }
  }

  const pruned = await pruneDeadTokens(deadTokens)
  return { attempted: uniqueTokens.length, sent, failed, pruned }
}

/**
 * Sends a push notification to all registered devices for the given user IDs.
 * Safe and non-throwing so callers never fail their primary API response.
 */
export async function sendPushToUsers(
  userIds: Array<number | string | null | undefined>,
  payload: PushPayload,
): Promise<PushDispatchResult> {
  const validIds = Array.from(
    new Set(
      userIds
        .map((id) => Number(id))
        .filter((id) => Number.isInteger(id) && id > 0),
    ),
  )
  if (validIds.length === 0) {
    return { attempted: 0, sent: 0, failed: 0, pruned: 0 }
  }

  try {
    await ensurePushTokensTable()
    const res = await pool.query<{ token: string }>(
      `SELECT token FROM public.user_push_tokens WHERE user_id = ANY($1::int[])`,
      [validIds],
    )
    const tokens = res.rows.map((r) => r.token)
    return await sendToTokens(tokens, payload)
  } catch (err) {
    console.warn("sendPushToUsers failed:", err)
    return { attempted: 0, sent: 0, failed: 0, pruned: 0 }
  }
}

/**
 * Sends a broadcast push notification to all registered customer devices.
 */
export async function sendPushToAllCustomers(
  payload: PushPayload,
): Promise<PushDispatchResult> {
  try {
    await ensurePushTokensTable()
    const res = await pool.query<{ token: string }>(`
      SELECT t.token
      FROM public.user_push_tokens t
      JOIN public.users u ON u.id = t.user_id
      WHERE LOWER(COALESCE(u.role, 'customer')) = 'customer'
    `)
    const tokens = res.rows.map((r) => r.token)
    return await sendToTokens(tokens, payload)
  } catch (err) {
    console.warn("sendPushToAllCustomers failed:", err)
    return { attempted: 0, sent: 0, failed: 0, pruned: 0 }
  }
}

/**
 * Sends a push notification to all registered admin and staff devices.
 */
export async function sendPushToAdmins(
  payload: PushPayload,
): Promise<PushDispatchResult> {
  try {
    await ensurePushTokensTable()
    const res = await pool.query<{ token: string }>(`
      SELECT t.token
      FROM public.user_push_tokens t
      JOIN public.users u ON u.id = t.user_id
      WHERE LOWER(COALESCE(u.role, '')) IN ('admin', 'staff')
         OR u.staff_role IS NOT NULL
    `)
    const tokens = res.rows.map((r) => r.token)
    return await sendToTokens(tokens, payload)
  } catch (err) {
    console.warn("sendPushToAdmins failed:", err)
    return { attempted: 0, sent: 0, failed: 0, pruned: 0 }
  }
}
